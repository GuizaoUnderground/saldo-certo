// Gera as capturas de tela usadas no TCC.
import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const p = await b.newPage({ viewport: { width: 1100, height: 900 }, deviceScaleFactor: 2 });
const erros = [];
p.on('pageerror', e => erros.push(e.message));
await p.goto('file:///home/claude/saldo-certo/web-preview/dist/local.html');
await p.evaluate(() => window.saldoCerto.recomecar('exemplo'));
await p.waitForTimeout(600);
const app = p.locator('#app');
const shot = async n => { await p.waitForTimeout(250); await app.screenshot({ path: `prints/${n}.png` }); };
const aba = n => p.getByRole('tab', { name: new RegExp(n) }).click();
await shot('01-inicio');
await app.getByRole('button', { name: '+ Registrar gasto ou receita' }).click();
await app.getByLabel('Valor (R$)', { exact: true }).fill('35,90');
await app.getByRole('button', { name: 'Supermercado', exact: true }).click();
await app.getByLabel('Descrição (opcional)', { exact: true }).fill('Padaria');
await shot('02-novo-lancamento');
await app.getByRole('button', { name: 'Salvar', exact: true }).click();
await aba('Lançamentos'); await shot('03-lancamentos');
await app.locator('[aria-label^="Excluir"]').first().click();
await shot('04-confirmar-exclusao');
await app.locator('[role=dialog] button', { hasText: 'Cancelar' }).click();
await aba('Relatório'); await shot('05-relatorio');
await p.evaluate(() => window.saldoCerto.recomecar('vazio')); await p.waitForTimeout(400);
await shot('06-inicio-vazio');
await p.evaluate(() => window.saldoCerto.recomecar('exemplo')); await p.waitForTimeout(400);
await p.screenshot({ path: 'prints/pagina.png' });
console.log('erros:', erros.length ? erros : 'nenhum');
await b.close();
