import { chromium } from '/home/claude/.npm-global/lib/node_modules/playwright/index.mjs';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const p = await b.newPage({ viewport: { width: 1100, height: 900 }, deviceScaleFactor: 2 });
const erros = [];
p.on('pageerror', e => erros.push('pageerror: ' + e.message));
p.on('console', m => { if (m.type() === 'error') erros.push('console: ' + m.text()); });
await p.goto('file:///home/claude/saldo-certo/web-preview/dist/local.html');
await p.waitForTimeout(800);
const app = p.locator('#app');
const shot = async n => { await p.waitForTimeout(250); await app.screenshot({ path: `prints/${n}.png` }); };
await shot('01-inicio');
await p.getByRole('tab', { name: /Lançamentos/ }).click(); await shot('02-lancamentos');
await p.getByRole('button', { name: '+ Novo' }).click();
await p.locator('#app input').first().fill('35,90');
await p.getByRole('button', { name: 'Supermercado', exact: true }).click();
await shot('03-novo-lancamento');
await p.getByRole('button', { name: 'Salvar', exact: true }).click(); await p.waitForTimeout(300);
await p.getByRole('tab', { name: /Metas/ }).click(); await shot('04-metas');
await p.getByRole('tab', { name: /Contas/ }).click(); await shot('05-contas');
await p.getByRole('button', { name: 'Paguei', exact: true }).first().click(); await p.waitForTimeout(300); await shot('05b-contas-paga');
await p.getByRole('tab', { name: /Relatório/ }).click(); await shot('06-relatorio');
// testa confirmação de exclusão
await p.getByRole('tab', { name: /Lançamentos/ }).click();
const antes = await p.locator('#app [aria-label^="Excluir"]').count();
await p.locator('#app [aria-label^="Excluir"]').first().click(); await p.waitForTimeout(200);
await shot('07-confirmar-exclusao');
await p.locator('#app [role=dialog] button', { hasText: 'Excluir' }).click(); await p.waitForTimeout(300);
const depois = await p.locator('#app [aria-label^="Excluir"]').count();
console.log('excluir:', antes, '->', depois);
// página inteira
await p.getByRole('tab', { name: /Início/ }).click();
await p.screenshot({ path: 'prints/pagina.png' });
await p.setViewportSize({ width: 400, height: 900 }); await p.waitForTimeout(300);
await p.screenshot({ path: 'prints/pagina-celular.png', fullPage: true });
console.log('ERROS:', erros.length ? erros : 'nenhum');
await b.close();
